/* Proves the date range does the two things that matter:
 *   1. the crawl STOPS once it scrolls past the start date, instead of
 *      scrolling a whole profile and throwing most of it away;
 *   2. it does not stop early on a feed that is not in date order.
 *
 * Runs the installed extension in real Chrome against a feed of 120 posts
 * whose dates come from their Instagram shortcodes, as on the real site. */
const { chromium } = require('playwright');
const path = require('path');
const fs = require('fs');

const EXT = process.env.EXT_DIR || path.resolve('chrome-scraper-extension');
const D = require('./chrome-scraper-extension/content/post_dates.js');

/* A real feed is longer than the 12-post overshoot guard, so the fixture has
 * to be too. Shortcodes are generated by running the real decoder backwards:
 * the date is encoded into the id exactly as Instagram does, which also means
 * the decoder has to round-trip for the test to work at all. */
const ALPHA = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_';
function codeForDate(ymd, salt) {
  const ms = new Date(ymd + 'T10:00:00Z').getTime();
  const id = ((BigInt(ms - D.IG_EPOCH_MS)) << 23n) + BigInt(salt % 8388608);
  let n = id, out = '';
  while (n > 0n) { out = ALPHA[Number(n % 64n)] + out; n /= 64n; }
  return out;
}
const DAY = 86400000;
const START = new Date('2026-11-11T00:00:00Z').getTime();
const ORDERED = Array.from({ length: 120 }, (_, i) =>
  codeForDate(new Date(START - i * DAY).toISOString().slice(0, 10), i * 7919));

const PAGE_SIZE = 6;

function buildHtml(mode) {
  let order = ORDERED;
  // one old post pinned to the top, as a page does
  if (mode === 'pinned') order = [ORDERED[ORDERED.length - 1], ...ORDERED.slice(0, -1)];
  // sorted by popularity rather than date - no usable order at all
  if (mode === 'shuffled') {
    order = ORDERED.slice();
    for (let i = order.length - 1; i > 0; i--) {
      const j = (i * 7919 + 13) % (i + 1);
      [order[i], order[j]] = [order[j], order[i]];
    }
  }
  return `<!DOCTYPE html><html><head><style>
    body{margin:0;font-family:system-ui}
    .cell{height:320px;border-bottom:1px solid #eee;padding:8px}
  </style></head><body><main><div class="grid" id="grid"></div></main>
  <script>
    const ALL = ${JSON.stringify(order)};
    let shown = 0;
    function addPage() {
      const g = document.getElementById('grid');
      ALL.slice(shown, shown + ${PAGE_SIZE}).forEach(code => {
        const d = document.createElement('div');
        d.className = 'cell';
        d.innerHTML = '<a href="/samsungindia/reel/' + code + '/"><div><img src="https://x/' +
          code + '.jpg"></div><span>12K</span></a>';
        g.appendChild(d);
      });
      shown = Math.min(shown + ${PAGE_SIZE}, ALL.length);
      window.__shown = shown;
    }
    addPage();
    addEventListener('scroll', () => {
      if (window.scrollY + innerHeight > document.body.scrollHeight - 400) addPage();
    });
  </script></body></html>`;
}

(async () => {
  let pass = 0, fail = 0;
  const ok = (n, c, extra) => { if (c) { console.log('  PASS', n); pass++; } else { console.log('  FAIL', n, extra || ''); fail++; } };

  const userDataDir = fs.mkdtempSync('/tmp/ss-daterange-');
  const context = await chromium.launchPersistentContext(userDataDir, {
    executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome',
    headless: false,
    args: ['--no-sandbox', `--disable-extensions-except=${EXT}`, `--load-extension=${EXT}`],
  });
  const sw = context.serviceWorkers()[0] || await context.waitForEvent('serviceworker', { timeout: 15000 });
  const extId = new URL(sw.url()).host;

  let mode = 'ordered';
  await context.route('**/*', route => {
    if (!/^https?:/i.test(route.request().url())) return route.continue();
    if (route.request().resourceType() === 'document') {
      return route.fulfill({ status: 200, contentType: 'text/html', body: buildHtml(mode) });
    }
    return route.fulfill({ status: 200, body: '' });
  });

  // A listener page stands in for the popup, which cannot be scripted.
  const listener = await context.newPage();
  await listener.goto(`chrome-extension://${extId}/offscreen/ocr.html`);
  await listener.evaluate(() => {
    window.__done = null;
    chrome.runtime.onMessage.addListener((m) => { if (m && m.type === 'crawlComplete') window.__done = m; });
  });

  async function crawl(from, maxScrolls) {
    await listener.evaluate(() => { window.__done = null; });
    const page = await context.newPage();
    await page.goto('https://www.instagram.com/samsungindia/reels/', { waitUntil: 'domcontentloaded' });
    await page.waitForTimeout(1200);
    const tabId = await sw.evaluate(async () => (await chrome.tabs.query({ url: '*://*.instagram.com/*' }))[0].id);
    await sw.evaluate(({ tabId, from, maxScrolls }) =>
      chrome.tabs.sendMessage(tabId, { action: 'startInfiniteScroll', tabId, maxScrolls, from, to: '' }),
    { tabId, from, maxScrolls });
    await listener.waitForFunction(() => window.__done !== null, { timeout: 60000 }).catch(() => {});
    const res = await listener.evaluate(() => window.__done);
    const loaded = await page.evaluate(() => window.__shown).catch(() => 0);
    await page.close();
    return { res, loaded };
  }

  const cutoff = '2026-10-20';
  console.log(`\n  feed has ${ORDERED.length} posts; asking for everything since ${cutoff}`);

  const limited = await crawl(cutoff, 40);
  ok('crawl completed', !!limited.res, 'no crawlComplete message');
  ok('it stopped because it reached the date, not the scroll limit',
    /reached 2026-10-20/.test((limited.res || {}).stopReason || ''), (limited.res || {}).stopReason);
  ok('it did NOT scroll the whole feed',
    limited.loaded < ORDERED.length, `loaded ${limited.loaded}/${ORDERED.length}`);
  ok('it still collected everything newer than the cutoff',
    (limited.res.allRows || []).filter(r => (r.Date || '') >= cutoff).length >=
      ORDERED.filter(c => D.ymd(D.igDateFromShortcode(c)) >= cutoff).length - 1,
    `${(limited.res.allRows || []).filter(r => (r.Date || '') >= cutoff).length} in range`);
  ok('it overshot past the cutoff rather than stopping on the first old post',
    (limited.res.allRows || []).filter(r => (r.Date || '') < cutoff).length >= 5,
    `${(limited.res.allRows || []).filter(r => (r.Date || '') < cutoff).length} older posts also collected`);
  ok('the feed was judged chronological', limited.res.chronological === true);

  console.log(`    stopped after loading ${limited.loaded} of ${ORDERED.length} posts — "${limited.res.stopReason}"`);

  // ── with no date set, the scroll limit governs ──────────────────────────
  const open = await crawl('', 3);
  ok('with no date range it runs to the scroll limit instead',
    /scroll limit/.test((open.res || {}).stopReason || ''), (open.res || {}).stopReason);

  // ── one pinned old post must NOT truncate the run ───────────────────────
  mode = 'pinned';
  const withPinned = await crawl(cutoff, 40);
  const pinnedInRange = (withPinned.res.allRows || []).filter(r => (r.Date || '') >= cutoff).length;
  ok('a single pinned old post does not cut the run short',
    pinnedInRange >= 20, `${pinnedInRange} posts in range collected`);
  ok('...and the feed is still treated as ordered, so it still stops early',
    withPinned.res.chronological === true && withPinned.loaded < ORDERED.length,
    `chronological=${withPinned.res.chronological} loaded=${withPinned.loaded}`);
  console.log(`    one pinned post: ${pinnedInRange} in range, loaded ${withPinned.loaded}/${ORDERED.length}`);

  // ── a feed with no date order at all must disable the shortcut ──────────
  mode = 'shuffled';
  // No early stop is possible here by design, so cap the scrolls: the point
  // is that the cutoff does NOT end it, not how far it would otherwise go.
  const shuffled = await crawl(cutoff, 6);
  const reason = (shuffled.res || {}).stopReason || '';
  ok('a feed sorted by something other than date is detected',
    shuffled.res.chronological === false, `chronological=${shuffled.res.chronological}`);
  ok('...and is never stopped by the date cutoff',
    !/reached 2026/.test(reason), `reason="${reason}"`);
  ok('...and explains why, rather than silently returning a short list',
    /not in date order/.test(reason), `reason="${reason}"`);

  console.log(`    shuffled feed: chronological=${shuffled.res.chronological}, "${reason}"`);

  console.log(`\n${pass} passed, ${fail} failed`);
  await context.close();
  process.exit(fail ? 1 : 0);
})();
